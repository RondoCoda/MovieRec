-- MovieRec PostgreSQL 18 schema. Run in an empty MovieRec database.
-- The names shared with MovieLens match sql/staging_to_final.sql.
-- Optional performance indexes are installed by C's benchmark configurations.

BEGIN;

CREATE TABLE users (
    user_id INTEGER PRIMARY KEY
);

CREATE TABLE movies (
    movie_id INTEGER PRIMARY KEY,
    title VARCHAR(300) NOT NULL,
    year SMALLINT
);

CREATE TABLE genres (
    genre_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE movie_genres (
    movie_id INTEGER NOT NULL REFERENCES movies (movie_id),
    genre_id INTEGER NOT NULL REFERENCES genres (genre_id),
    PRIMARY KEY (movie_id, genre_id)
);

CREATE TABLE ratings (
    user_id INTEGER NOT NULL REFERENCES users (user_id),
    movie_id INTEGER NOT NULL REFERENCES movies (movie_id),
    -- Preserve incoming precision so 4.54 is rejected instead of rounded to 4.5.
    rating NUMERIC NOT NULL,
    -- The importer and the application store UTC wall-clock values here.
    rated_at TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    PRIMARY KEY (user_id, movie_id),
    CONSTRAINT ratings_half_star CHECK (
        rating BETWEEN 0.5 AND 5.0 AND mod(rating, 0.5) = 0
    )
);

CREATE TABLE tags (
    tag_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    CONSTRAINT tags_normalized_name CHECK (name <> '' AND name = lower(btrim(name)))
);

CREATE TABLE movie_tags (
    user_id INTEGER NOT NULL REFERENCES users (user_id),
    movie_id INTEGER NOT NULL REFERENCES movies (movie_id),
    tag_id INTEGER NOT NULL REFERENCES tags (tag_id),
    tagged_at TIMESTAMP NOT NULL,
    PRIMARY KEY (user_id, movie_id, tag_id)
);

CREATE TABLE links (
    movie_id INTEGER PRIMARY KEY REFERENCES movies (movie_id),
    imdb_id VARCHAR(10),
    tmdb_id INTEGER
);

-- One row per watch event. MovieLens does not populate this table.
CREATE TABLE watch_history (
    watch_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users (user_id),
    movie_id INTEGER NOT NULL REFERENCES movies (movie_id),
    watched_at TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);

COMMIT;
